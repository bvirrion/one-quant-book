#!/usr/bin/env python3
"""Generate parts/<slug>/tracks.tex, the role and firm-type table of a book's preface, from the question tags.

Usage: .venv/bin/python tools/make_interview_tracks.py interviews-1. A cell counts the chapter's questions tagged for
that role. A blank cell means none. Timed tests and drill sheets carry no tags and are for everyone, so they are left
out.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ROLES = ["QR", "QT", "Trader", "Analyst", "DS", "QD", "Dev", "LLE", "Risk"]
FIRMS = [("market maker", "MM"), ("crypto", "Cr"), ("bank", "Bk"), ("hedge fund", "HF")]
OPT = re.compile(r"\\begin\{question\}\[((?:[^\[\]]|\[[^\]]*\])*)\]")


def tag(opt, name):
    m = re.search(r"\\" + name + r"\{([^}]*)\}", opt)
    return [x.strip() for x in m.group(1).split(",")] if m else []


def main(book):
    parts = ROOT / "parts" / book
    prefix = "iv" + book.rsplit("-", 1)[1]
    rows = []
    stems = re.findall(r"\\ominput\{[^}]+\}\{([^}]+)\}", (parts / "part.tex").read_text(encoding="utf-8"))
    for stem in stems:
        slug = stem.split("-", 1)[1]
        body = (parts / f"{stem}.tex").read_text(encoding="utf-8")
        opts = OPT.findall(body)
        if not opts:
            continue
        title = re.search(r"\\chapter\{([^}]*)\}", body).group(1)
        cells = [sum(role in tag(o, "iqroles") for o in opts) for role in ROLES]
        cells += [sum(key in tag(o, "iqfirm") or "any" in tag(o, "iqfirm") for o in opts) for key, _ in FIRMS]
        rows.append((slug, title, cells))
    heads = ROLES + [short for _, short in FIRMS]
    out = [
        "% Generated by tools/make_interview_tracks.py. Do not edit.",
        r"\section*{Which chapters to train on}",
        r"Each cell counts the questions in a chapter tagged for that role or type of firm. QR is quantitative "
        r"researcher, QT quantitative trader, DS data scientist, QD quantitative developer, Dev software developer, "
        r"LLE low-latency engineer, Risk risk quant; MM market maker, Cr crypto firm, Bk bank, HF hedge fund. "
        r"Untagged tests and drills are for everyone.",
        r"\par\medskip\noindent{\footnotesize\setlength{\tabcolsep}{2.5pt}%",
        r"\begin{tabular}{@{}l" + "r" * len(heads) + "@{}}",
        r"\hline",
        "Chapter & " + " & ".join(heads) + r" \\",
        r"\hline",
    ]
    for slug, title, cells in rows:
        shown = " & ".join(str(c) if c else "" for c in cells)
        out.append(rf"\hyperref[ch:{prefix}:{slug}]{{{title}}} & {shown} \\")
    out += [r"\hline", r"\end{tabular}}", ""]
    (parts / "tracks.tex").write_text("\n".join(out), encoding="utf-8")
    print(f"{book}/tracks.tex: {len(rows)} chapters")


if __name__ == "__main__":
    main(sys.argv[1])
