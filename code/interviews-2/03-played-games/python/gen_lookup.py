"""Write the scrambled result tables of the played games. A solo player reads only the cell for their own bid.

Run: python gen_lookup.py. The other player's value stays out of sight, because no reader scans a shuffled row for a
threshold by accident. Game 1, S: they sell you one lot at your bid. B: they buy one lot at your ask. P: they pass.
Game 3, W: your bid wins the lot. L: your bid loses it.
"""
import pathlib
import random
from fractions import Fraction as F

ROOT = pathlib.Path(__file__).resolve().parents[4]
OUT = ROOT / "parts" / "interviews-2" / "generated"

# Round: (the other player's value, width of the quote, lowest bid listed, highest bid listed).
ROUNDS = {1: (F(124, 9), 2, 10, 20), 2: (F(124, 9), 2, 10, 20), 3: (F(33, 2), 2, 13, 21), 4: (F(17), 1, 14, 20)}
# Game 3, the auction. Round: the rival's bid on the dice dealt. You bid from 0 to 20 in steps of 0.5.
AUCTION = {1: F(4), 2: F(8), 3: F(14)}
AUCTION_BIDS = [F(i, 2) for i in range(41)]


def result(value, width, bid):
    if bid > value:
        return "S"
    return "B" if bid + width < value else "P"


def table(number):
    value, width, low, high = ROUNDS[number]
    bids = [F(low) + F(i, 2) for i in range(2 * (high - low) + 1)]
    random.Random(1000 + number).shuffle(bids)
    return [(float(b), result(value, width, b)) for b in bids]


def auction_table(number):
    bids = list(AUCTION_BIDS)
    random.Random(3000 + number).shuffle(bids)
    return [(float(b), "W" if b > AUCTION[number] else "L") for b in bids]


def write(out=OUT):
    out.mkdir(exist_ok=True)
    for number in AUCTION:
        cells = "\\quad ".join(f"\\ivcell{{{b:.1f}}}{{{r}}}" for b, r in auction_table(number))
        (out / f"game-3-round-{number}.tex").write_text(
            "% Generated by code/interviews-2/03-played-games/python/gen_lookup.py. Do not edit.\n"
            f"\\ivlookup{{{cells}}}\n",
            encoding="utf-8",
        )
    for number in ROUNDS:
        cells = "\\quad ".join(f"\\ivcell{{{b:.1f}}}{{{r}}}" for b, r in table(number))
        (out / f"game-1-round-{number}.tex").write_text(
            "% Generated by code/interviews-2/03-played-games/python/gen_lookup.py. Do not edit.\n"
            f"\\ivlookup{{{cells}}}\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    write()
